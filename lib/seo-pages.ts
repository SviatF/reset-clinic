export function normalizeSeoPath(path: string) {
  if (!path.startsWith("/")) path = `/${path}`;
  return path.endsWith("/") ? path : `${path}/`;
}

export function getSeoLanding(path: string) {
  const normalized = normalizeSeoPath(path);
  return SEO_LANDINGS.find((item) => item.path === normalized);
}

export function buildSeoLandingMetadata(landing: SeoLanding): Metadata {
  return {
    title: landing.title,
    description: landing.description,
    alternates: { canonical: landing.path },
    openGraph: {
      type: "website",
      locale: "uk_UA",
      url: landing.path,
      siteName: SITE_NAME,
      title: landing.title,
      description: landing.description,
      images: [{ url: DEFAULT_OG_IMAGE, width: 2446, height: 1314, alt: `${landing.h1} — ${SITE_NAME}` }],
    },
    twitter: { card: "summary_large_image", title: landing.title, description: landing.description, images: [DEFAULT_OG_IMAGE] },
    robots: {
      index: true,
      follow: true,
      googleBot: { index: true, follow: true, "max-image-preview": "large", "max-snippet": -1, "max-video-preview": -1 },
    },
  };
}

export function buildSeoLandingJsonLd(landing: SeoLanding) {
  const url = `${SITE_URL}${landing.path}`;
  const pageType = landing.type === "category" ? "CollectionPage" : "MedicalWebPage";
  const graph: Record<string, unknown>[] = [
    {
      "@type": pageType,
      "@id": `${url}#webpage`,
      url,
      name: landing.title,
      headline: landing.h1,
      description: landing.description,
      inLanguage: "uk-UA",
      isPartOf: { "@id": `${SITE_URL}/#website` },
      about: { "@id": `${SITE_URL}/#clinic` },
      breadcrumb: { "@id": `${url}#breadcrumb` },
      primaryImageOfPage: { "@type": "ImageObject", url: `${SITE_URL}${DEFAULT_OG_IMAGE}` },
    },
    {
      "@type": "BreadcrumbList",
      "@id": `${url}#breadcrumb`,
      itemListElement: landing.breadcrumbs.map((crumb, index) => ({
        "@type": "ListItem",
        position: index + 1,
        name: crumb.name,
        item: `${SITE_URL}${crumb.href}`,
      })),
    },
  ];

  if (landing.type === "service" || landing.type === "procedure") {
    graph.push({
      "@type": "Service",
      "@id": `${url}#service`,
      name: landing.h1,
      description: landing.description,
      url,
      provider: { "@id": `${SITE_URL}/#clinic` },
      areaServed: { "@type": "City", name: clinic.city },
    });
  }

  if (landing.faq.length) {
    graph.push({
      "@type": "FAQPage",
      "@id": `${url}#faq`,
      mainEntity: landing.faq.map((item) => ({
        "@type": "Question",
        name: item.question,
        acceptedAnswer: { "@type": "Answer", text: item.answer },
      })),
    });
  }

  return { "@context": "https://schema.org", "@graph": graph };
}
