export const PL_PROMO_SLUGS = Object.values(PL_PROMO_PATHS);

export function getPolishPromoByPathSlug(pathSlug: string) {
  const entry = (Object.entries(PL_PROMO_PATHS) as Array<[PromoServiceSlug, string]>)
    .find(([, value]) => value === pathSlug);
  return entry ? PROMO_SERVICES_PL[entry[0]] : undefined;
}

export function polishPromoPath(slug: PromoServiceSlug, quiz = false) {
  return `/pl/promo/${PL_PROMO_PATHS[slug]}/${quiz ? "quiz/" : ""}`;
}
